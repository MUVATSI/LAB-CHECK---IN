    private void rafraichirOccupation() {
        try {
            LaborDAO laborDAO = new LaborDAO();
            PresenceDAO presDAO = new PresenceDAO();

            // 1. Compter les présents actuels
            int presents = laborDAO.getPresentsActuelsCount(laborActif.getIdLabo());
            int max = laborActif.getCapaciteMax();

            // 2. Calculer le pourcentage
            int pourcentage = (max > 0) ? (presents * 100 / max) : 0;

            // 3. Mettre à jour tes labels et ta jProgressBar
            // (Remplace les noms de variables ci-dessous par les nôtres si différents)
            placeBtn.setText(presents + " / " + max + " Places");
            occBtn.setText(pourcentage + " %");
            jProgressBar1.setMaximum(max);
            jProgressBar1.setValue(presents);

        } catch (Exception e) {
            System.out.println("Erreur jauge : " + e.getMessage());
        }
    }
    
