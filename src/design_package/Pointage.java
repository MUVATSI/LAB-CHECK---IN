    private void validPrBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_validPrBtnActionPerformed
        // TODO add your handling code here:                                           
            String matricule = txtMatricule.getText().trim();
            String motif = cmbMotif.getSelectedItem() != null ? cmbMotif.getSelectedItem().toString() : "Autre";

            // 1. Contrôle de saisie
            if (matricule.isEmpty()) {
                statusLabel.setText("Saisissez le Matricule SVP !");
                statusLabel.setForeground(java.awt.Color.RED);
                return;
            }

            try {
                LabUserDAO userDAO = new LabUserDAO();
                PresenceDAO presenceDAO = new PresenceDAO();

                // 2. Rechercher l'étudiant
                LabUser user = userDAO.findByMatricule(matricule);
                if (user == null) {
                    statusLabel.setText("Matricule " + matricule + " introuvable !");
                    statusLabel.setForeground(java.awt.Color.RED);
                    txtMatricule.selectAll();
                    return;
                }

                // 3. Effectuer le pointage (Entrée ou Sortie)
                String resultat = presenceDAO.pointer(user, laborActif, motif);

                // 4. Afficher le message sur ton JLabel (ex: lblStatus - ton label "Bienvenue")
                statusLabel.setText(resultat);
                if (resultat.startsWith("SORTIE")) {
                    statusLabel.setForeground(java.awt.Color.BLUE);
                } else if (resultat.startsWith("ENTRÉE")) {
                    statusLabel.setForeground(new java.awt.Color(0, 128, 0)); // Vert
                } else {
                    statusLabel.setForeground(java.awt.Color.RED);
                }

                // 5. Nettoyer le champ texte & rafraîchir la jauge d'occupation
                txtMatricule.setText("");
                txtMatricule.requestFocus();
                rafraichirOccupation();

            } catch (Exception e) {
                statusLabel.setText("Erreur BD : " + e.getMessage());
                statusLabel.setForeground(java.awt.Color.RED);
            }  
    }//GEN-LAST:event_validPrBtnActionPerformed

